// Copies the TypeScript types that zodiak-api generates from its Rust protocol crate.
// Usage: npm run protocol:sync [path-to-zodiak-api]
const { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } = require('node:fs')
const { join, resolve } = require('node:path')

const api = resolve(process.argv[2] ?? join(__dirname, '..', '..', 'zodiak-api'))
const source = join(api, 'bindings')
const target = join(__dirname, '..', 'src', 'shared', 'protocol')

if (!existsSync(source)) {
  console.error(`No bindings found at ${source}. Run "cargo test -p zodiak-protocol" in zodiak-api first.`)
  process.exit(1)
}

rmSync(target, { recursive: true, force: true })
mkdirSync(target, { recursive: true })
const files = readdirSync(source).filter((file) => file.endsWith('.ts')).sort()
for (const file of files) cpSync(join(source, file), join(target, file))
const index = files.map((file) => `export type * from './${file.slice(0, -3)}'`).join('\n')
writeFileSync(join(target, 'index.ts'), `// Generated by scripts/sync-protocol.cjs. Do not edit.\n${index}\n`)
console.log(`Copied ${files.length} protocol types to ${target}`)
